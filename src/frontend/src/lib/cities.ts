// Strip "гр.", "с.", "общ.", "кв." etc. prefixes and normalize whitespace.
export function normalizeCity(raw: string): string {
	return raw
		.replace(/^(гр\.|с\.|общ\.|кв\.|р-н\s+)\s*/i, '')
		.replace(/\s+/g, ' ')
		.trim();
}

export function getCityCoords(locality: string | null | undefined): [number, number] | null {
	if (!locality) return null;
	const name = normalizeCity(locality);
	return CITY_COORDS[name] ?? null;
}
